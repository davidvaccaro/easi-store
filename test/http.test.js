import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import http from 'node:http';
import { createStoreServer } from '../src/server.js';
import { createDicom, uid } from './fixtures/synthetic.js';

test('HTTP archive: setup, original import/retrieve, authenticated catalog, restart, CSRF and host protection', async t => {
    const dataDir = await mkdtemp(path.join(tmpdir(), 'easi-store-http-'));
    let app = await createStoreServer({ dataDir, port: 0 });
    let address = await app.listen(); let base = `http://127.0.0.1:${address.port}`;
    t.after(async () => { await app.close(); await rm(dataDir, { recursive: true, force: true }); });
    let response = await fetch(base + '/api/v1/session');
    assert.deepEqual(await response.json(), { authenticated: false, setupRequired: true, bootstrapRequired: false });
    assert.equal((await fetch(base + '/api/v1/summary')).status, 401);
    assert.equal((await fetch(base + '/dicomweb/studies')).status, 401);
    response = await fetch(base + '/api/v1/setup', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-EASI-Store': '1' }, body: JSON.stringify({ username: 'research', password: 'synthetic-test-password' }) });
    assert.equal(response.status, 200); const cookie = response.headers.get('set-cookie').split(';')[0];
    assert.match(response.headers.get('set-cookie'), /HttpOnly; SameSite=Strict/);
    const headers = { Cookie: cookie, 'X-EASI-Store': '1' };
    assert.equal((await fetch(base + '/api/v1/setup', { method: 'POST', headers: { ...headers, 'Content-Type': 'application/json' }, body: '{}' })).status, 409);
    const studyUid = uid(), seriesUid = uid(), sopUid = uid(), bytes = createDicom({ studyUid, seriesUid, sopUid });
    response = await fetch(base + '/api/v1/instances', { method: 'POST', headers: { ...headers, 'Content-Type': 'application/dicom' }, body: bytes });
    assert.equal(response.status, 201, JSON.stringify(await response.clone().json()));
    const stored = await response.json(); assert.equal(stored.status, 'stored');
    assert.equal(stored.instance.sopUid, sopUid);
    response = await fetch(base + '/api/v1/summary', { headers }); const counts = await response.json();
    assert.equal(counts.instances, 1); assert.equal(counts.studies, 1); assert.equal(counts.patients, 1);
    response = await fetch(base + `/api/v1/download/${studyUid}/${seriesUid}/${sopUid}`, { headers });
    assert.equal(response.status, 200); assert.deepEqual(Buffer.from(await response.arrayBuffer()), bytes);
    response = await fetch(base + '/api/v1/instances', { method: 'POST', headers: { ...headers, 'Content-Type': 'application/dicom' }, body: bytes }); assert.equal(response.status, 200);
    assert.equal((await response.json()).status, 'duplicate');
    assert.equal((await fetch(base + '/api/v1/instances', { method: 'POST', headers: { Cookie: cookie, 'Content-Type': 'application/dicom' }, body: bytes })).status, 403);
    assert.equal((await fetch(base + '/api/v1/instances', { method: 'POST', headers: { ...headers, Origin: 'https://unrelated.invalid', 'Content-Type': 'application/dicom' }, body: bytes })).status, 403);
    const hostileStatus = await new Promise((resolve, reject) => { const request = http.get(base + '/api/health', { headers: { Host: 'attacker.invalid' } }, result => { result.resume(); resolve(result.statusCode); }); request.on('error', reject); });
    assert.equal(hostileStatus, 403);
    assert.equal((await fetch(base + '/api/v1/studies?limit=NaN', { headers })).status, 400);
    const token = await app.auth.issueApiToken('Synthetic integration test');
    assert.equal((await fetch(base + '/api/v1/summary', { headers: { Authorization: `Bearer ${token}` } })).status, 200);
    assert.equal((await fetch(base + '/api/v1/summary', { headers: { Authorization: 'Bearer invalid' } })).status, 401);
    await app.close(); app = await createStoreServer({ dataDir, port: 0 }); address = await app.listen(); base = `http://127.0.0.1:${address.port}`;
    assert.equal((await fetch(base + '/api/v1/summary', { headers: { Cookie: cookie } })).status, 401, 'browser sessions expire at server restart');
    response = await fetch(base + '/api/v1/summary', { headers: { Authorization: `Bearer ${token}` } });
    assert.equal(response.status, 200); assert.equal((await response.json()).instances, 1);
    response = await fetch(base + '/api/v1/login', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-EASI-Store': '1' }, body: JSON.stringify({ username: 'research', password: 'synthetic-test-password' }) });
    assert.equal(response.status, 200);
});

test('authentication supports non-loopback bootstrap without a shared default password', async t => {
    const dataDir = await mkdtemp(path.join(tmpdir(), 'easi-store-bootstrap-'));
    const { Auth } = await import('../src/http/Auth.js'); const auth = await new Auth(dataDir).open();
    t.after(() => rm(dataDir, { recursive: true, force: true }));
    await assert.rejects(auth.setup({ username: 'research', password: 'synthetic-test-password' }, '172.18.0.1'), /bootstrap token/);
    await auth.setup({ username: 'research', password: 'synthetic-test-password', bootstrapToken: auth.bootstrap }, '172.18.0.1');
    const concurrentDir = await mkdtemp(path.join(tmpdir(), 'easi-store-race-')); t.after(() => rm(concurrentDir, { recursive: true, force: true }));
    const second = await new Auth(concurrentDir).open();
    const results = await Promise.allSettled([second.setup({ username: 'first', password: 'synthetic-test-password' }, '127.0.0.1'), second.setup({ username: 'second', password: 'synthetic-test-password' }, '127.0.0.1')]);
    assert.equal(results.filter(result => result.status === 'fulfilled').length, 1); assert.equal(second.record.username, 'first');
});
